"""Reproduce baseline/protected outcomes; no LLM or network requests."""
import json
import platform
from pathlib import Path
from gramhelp import Gateway, VulnerableGateway, Session, Ticket, Document, Denied, render_output

HERE = Path(__file__).resolve().parent


def run():
    student = Session('student-a', 'student')
    staff = Session('staff-a', 'staff')
    vulnerable = VulnerableGateway()
    protected = Gateway()
    rows = []

    def check(name, expected, operation):
        try:
            value = operation()
            observed = value if isinstance(value, str) else 'allowed'
        except Denied:
            observed = 'denied'
        rows.append({'case': name, 'expected': expected, 'observed': observed, 'pass': observed == expected})

    # The same attacker-selected target is sent to each implementation.
    check('baseline_cross_student_balance', 'allowed', lambda: vulnerable.balance(student, 'student-b'))
    check('protected_cross_student_balance', 'denied', lambda: protected.balance(student, 'student-b'))
    ticket = Ticket('Urgent verification', 'Synthetic unwanted ticket')
    check('baseline_unapproved_ticket', 'allowed', lambda: vulnerable.execute_ticket(student, ticket))
    p = protected.propose_ticket(student, ticket)
    check('protected_unapproved_ticket', 'denied', lambda: protected.execute_ticket(student, p, ''))
    token = protected.approve_ticket(student, p)
    check('protected_approved_ticket', 'allowed', lambda: protected.execute_ticket(student, p, token))
    check('protected_replayed_approval', 'denied', lambda: protected.execute_ticket(student, p, token))

    malicious = (HERE / 'fixtures/injected-policy.txt').read_text(encoding='utf-8')
    check('unreviewed_upload', 'denied', lambda: protected.publish_document(staff, Document('unreviewed', malicious, 'public', False)))
    protected.publish_document(staff, Document('reviewed-malicious', malicious, 'public', True))
    protected.publish_document(staff, Document('staff-only', 'Synthetic private guidance', 'staff', True))
    docs = protected.retrieve(student)
    check('reviewed_injection_retrievable', 'yes', lambda: 'yes' if any(d.text == malicious for d in docs) else 'no')
    check('staff_document_excluded', 'yes', lambda: 'yes' if all(d.id != 'staff-only' for d in docs) else 'no')
    check('html_escaped', 'yes', lambda: 'yes' if '<script>' not in render_output('<script>alert(1)</script>') else 'no')
    limited = Gateway(limit=2)
    limited.balance(student, 'student-a'); limited.balance(student, 'student-a')
    check('third_request_over_quota', 'denied', lambda: limited.balance(student, 'student-a'))

    result = {'scope': 'Deterministic control simulation; tool arguments supplied directly, not generated by an LLM.',
              'python': platform.python_version(), 'cases': rows,
              'audit': protected.audit, 'all_passed': all(r['pass'] for r in rows)}
    out = HERE / 'evidence'
    out.mkdir(exist_ok=True)
    (out / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    lines = ['# Measured control demonstration', '', result['scope'], '',
             '| Case | Expected | Observed | Pass |', '| --- | --- | --- | --- |']
    lines.extend(f"| {r['case']} | {r['expected']} | {r['observed']} | {r['pass']} |" for r in rows)
    lines += ['', 'The baseline allows two unsafe actions. The protected gateway blocks them. A reviewed malicious document remains retrievable: review is not proof of semantic safety.',
              '', 'No model attack-success rate, real RAG performance, PDF scanning effectiveness, or production security claim is measured.']
    (out / 'results.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f"{sum(r['pass'] for r in rows)}/{len(rows)} expected outcomes reproduced")
    if not result['all_passed']: raise SystemExit(1)


if __name__ == '__main__': run()
